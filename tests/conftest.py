"""Collects scenario results during the pytest run and writes the eval table.
The table is therefore generated by the test run itself, not written by hand."""
import csv
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

RESULTS = []


def pytest_sessionfinish(session, exitstatus):
    if not RESULTS:
        return
    os.makedirs(os.path.join(ROOT, "reports"), exist_ok=True)
    from evals.scenarios import SCENARIOS
    # a filtered run (pytest -k ...) must not overwrite the full table
    stem = "eval_table" if len(RESULTS) == len(SCENARIOS) else "eval_table.partial"
    order = {r.scenario.id: i for i, r in enumerate(RESULTS)}
    rows = sorted(RESULTS, key=lambda r: r.scenario.id)
    md = ["# Eval table", "",
          "Generated by `pytest tests/test_scenarios.py` (offline RuleModel, seeded mocks). "
          "Each scenario also asserts the global invariants listed at the bottom.", "",
          f"**{sum(r.passed for r in rows)}/{len(rows)} scenarios passed**", "",
          "| Scenario | Category | Expected | Actual | Pass/Fail | Notes |", "|---|---|---|---|---|---|"]
    for r in rows:
        failed = [c for c in r.checks if not c[1]]
        notes = ("; ".join(f"FAILED {c[0]}: {c[2]}" for c in failed) if failed else
                 f"{len(r.checks)} checks: " + "; ".join(c[0] for c in r.checks if not c[0].startswith("INV")))
        if r.error:
            notes = "ERROR: " + r.error.strip().splitlines()[-1]
        esc = lambda s: str(s).replace("|", "\\|").replace("\n", " ")
        md.append(f"| {r.scenario.id} | {r.scenario.category} | {esc(r.scenario.expected)} | {esc(r.actual)} | "
                  f"{'✅ pass' if r.passed else '❌ FAIL'} | {esc(notes)} |")
    inv = sorted({c[0] for r in rows for c in r.checks if c[0].startswith("INV")})
    md += ["", "Global invariants checked in every scenario:", ""] + [f"- {i}" for i in inv]
    with open(os.path.join(ROOT, "reports", f"{stem}.md"), "w") as f:
        f.write("\n".join(md) + "\n")
    with open(os.path.join(ROOT, "reports", f"{stem}.csv"), "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["scenario", "category", "expected", "actual", "pass_fail", "checks"])
        for r in rows:
            w.writerow([r.scenario.id, r.scenario.category, r.scenario.expected, r.actual,
                        "pass" if r.passed else "fail", " | ".join(f"{c[0]}={'ok' if c[1] else 'FAIL'}" for c in r.checks)])
